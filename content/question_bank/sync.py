#!/usr/bin/env python3
"""Keep every copy of the question bank in step with the source.

content/question_bank/ is the only place questions are edited. This
script writes the derived files from it:

  app/assets/questions.json                               (byte copy)
  backend/supabase/functions/grade-attempt/questions.json (byte copy)
  backend/supabase/seed.sql                               (skills + questions rows)

  python3 content/question_bank/sync.py          # rewrite the copies
  python3 content/question_bank/sync.py --check  # exit 1 if any copy drifted

Run validate.py first; this script trusts the bank's shape.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BANK = ROOT / "content/question_bank"
QUESTIONS = BANK / "questions.json"
SKILLS = BANK / "skills.json"

COPIES = [
    ROOT / "app/assets/questions.json",
    ROOT / "backend/supabase/functions/grade-attempt/questions.json",
]
SEED = ROOT / "backend/supabase/seed.sql"


def sql_str(value):
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def seed_sql(questions, taxonomy):
    lines = [
        "-- Generated by content/question_bank/sync.py. Do not edit by hand.",
        "-- Loaded by `supabase db reset` for local development and tests.",
        "",
        "insert into skills (slug, section, domain, sat_weight) values",
    ]
    rows = []
    for domain in taxonomy["domains"]:
        # The domain's weight is split evenly across its skills.
        weight = domain["sat_weight"] / len(domain["skills"])
        for skill in domain["skills"]:
            rows.append(
                f"  ({sql_str(skill)}, {sql_str(domain['section'])}, "
                f"{sql_str(domain['domain'])}, {round(weight, 6)})"
            )
    lines.append(",\n".join(rows))
    lines.append("on conflict (slug) do update set section = excluded.section,")
    lines.append("  domain = excluded.domain, sat_weight = excluded.sat_weight;")
    lines.append("")
    lines.append(
        "insert into questions (slug, section, skill, difficulty, tier, four_d, "
        "passage, time_target_seconds, stem, choices, correct_index, "
        "explanation, reviewed) values"
    )
    rows = []
    for q in questions:
        rows.append(
            "  ("
            + ", ".join(
                [
                    sql_str(q["id"]),
                    sql_str(q["section"]),
                    sql_str(q["skill"]),
                    str(q["difficulty"]),
                    sql_str(q["tier"]),
                    sql_str(q["four_d"]),
                    sql_str(q.get("passage")),
                    str(q.get("time_target_seconds") or "null"),
                    sql_str(q["stem"]),
                    sql_str(json.dumps(q["choices"], ensure_ascii=False)) + "::jsonb",
                    str(q["correct_index"]),
                    sql_str(q["explanation"]),
                    "true" if q.get("reviewed") else "false",
                ]
            )
            + ")"
        )
    lines.append(",\n".join(rows))
    lines.append(
        "on conflict (slug) do update set section = excluded.section, "
        "skill = excluded.skill,"
    )
    lines.append(
        "  difficulty = excluded.difficulty, tier = excluded.tier, "
        "four_d = excluded.four_d,"
    )
    lines.append(
        "  passage = excluded.passage, "
        "time_target_seconds = excluded.time_target_seconds,"
    )
    lines.append(
        "  stem = excluded.stem, choices = excluded.choices, "
        "correct_index = excluded.correct_index,"
    )
    lines.append(
        "  explanation = excluded.explanation, reviewed = excluded.reviewed;"
    )
    return "\n".join(lines) + "\n"


def expected_files():
    source = QUESTIONS.read_bytes()
    questions = json.loads(source)
    taxonomy = json.loads(SKILLS.read_text())
    files = {path: source for path in COPIES}
    files[SEED] = seed_sql(questions, taxonomy).encode()
    return files


def main():
    check = "--check" in sys.argv[1:]
    drifted = []
    for path, content in expected_files().items():
        current = path.read_bytes() if path.exists() else None
        if current == content:
            continue
        drifted.append(path.relative_to(ROOT))
        if not check:
            path.write_bytes(content)

    if check and drifted:
        print("Out of sync with content/question_bank/:")
        for path in drifted:
            print(f"  {path}")
        print("Run: python3 content/question_bank/sync.py")
        sys.exit(1)
    if not check:
        for path in drifted:
            print(f"wrote {path}")
    print("question bank copies in sync")


if __name__ == "__main__":
    main()
